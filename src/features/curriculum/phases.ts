export function getPhase(slug: string) {
  return PHASES.find((phase) => phase.slug === slug)
}

export function getPhaseByPosition(position: number) {
  return PHASES.find((phase) => phase.position === position)
}

export function getPhaseForDay(dayNumber: number) {
  return PHASES.find((phase) => dayNumber >= phase.startDay && dayNumber <= phase.endDay)
}