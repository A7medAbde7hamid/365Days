/**
 * Generate supabase/seed/curriculum.sql from the TypeScript curriculum.
 *
 *   npm run seed:curriculum
 *
 * The curriculum is authored in TypeScript (single source of truth for the app)
 * but the app needs a database UUID for every day in order to write progress.
 * This script bridges the two by emitting deterministic UUIDs, so re-running it
 * produces stable ids and the SQL can be applied more than once safely
 * (every statement is an idempotent upsert).
 *
 * Apply the result with the Supabase SQL editor or `psql`. It is deliberately a
 * file rather than a live connection, so it never needs a service-role key.
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { globSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const base = new URL('../src/features/curriculum/', import.meta.url)
const { PHASES } = await import(new URL('phases.ts', base).href)

// Discover every authored phase file so a new phase-*.ts is picked up without
// editing this script.
const dayFiles = globSync('days/phase-*.ts', { cwd: fileURLToPath(base) }).sort((a, b) =>
  a.localeCompare(b, 'en', { numeric: true }),
)

const ALL_DAYS = []
for (const file of dayFiles) {
  const mod = await import(new URL(file, base).href)
  for (const [name, days] of Object.entries(mod)) {
    if (/^PHASE_\d+_DAYS$/.test(name)) ALL_DAYS.push(...days)
  }
}

ALL_DAYS.sort((a, b) => a.dayNumber - b.dayNumber)

if (ALL_DAYS.length === 0) {
  console.error('No curriculum days found.')
  process.exit(1)
}

// Fixed namespace so generated ids are stable across runs and machines.
const NAMESPACE = '6f9619ff-8b86-d011-b42d-00c04fc964ff'

/** UUID v5 (SHA-1, name-based) — matches RFC 4122 version 5. */
function uuidv5(name) {
  const ns = Buffer.from(NAMESPACE.replace(/-/g, ''), 'hex')
  const hash = createHash('sha1').update(ns).update(Buffer.from(name, 'utf8')).digest()
  const bytes = Buffer.from(hash.subarray(0, 16))
  bytes[6] = (bytes[6] & 0x0f) | 0x50 // version 5
  bytes[8] = (bytes[8] & 0x3f) | 0x80 // variant 10xx
  const hex = bytes.toString('hex')
  return [
    hex.slice(0, 8),
    hex.slice(8, 12),
    hex.slice(12, 16),
    hex.slice(16, 20),
    hex.slice(20, 32),
  ].join('-')
}

const phaseId = (slug) => uuidv5(`phase:${slug}`)
const dayId = (n) => uuidv5(`day:${n}`)
const taskId = (n, pos) => uuidv5(`task:${n}:${pos}`)
const resourceId = (n, i) => uuidv5(`resource:${n}:${i}`)

/** Escape a value for a single-quoted SQL literal. */
function q(value) {
  if (value === null || value === undefined) return 'NULL'
  return `'${String(value).replace(/'/g, "''")}'`
}

/** Escape a Postgres array literal of strings. */
function arr(values) {
  if (!values || values.length === 0) return "'{}'::text[]"
  return `ARRAY[${values.map(q).join(', ')}]::text[]`
}

/** Escape a Postgres array literal of integers (e.g. prerequisites). */
function intArr(values) {
  if (!values || values.length === 0) return "'{}'::integer[]"
  return `ARRAY[${values
    .map((v) => {
      const n = Number(v)
      if (!Number.isInteger(n)) throw new Error(`Non-integer prerequisite: ${v}`)
      return String(n)
    })
    .join(', ')}]::integer[]`
}

const out = []
out.push('-- =============================================================================')
out.push('-- Generated by: npm run seed:curriculum')
out.push(`-- Days: ${ALL_DAYS.length} of 365   Phases: ${PHASES.length}`)
out.push('--')
out.push('-- Do not edit by hand. Edit src/features/curriculum/days/*.ts and re-run.')
out.push('-- Every statement is an idempotent upsert with a deterministic UUID, so it')
out.push('-- is safe to apply repeatedly.')
out.push('-- =============================================================================')
out.push('')
out.push('BEGIN;')
out.push('')

// --- Phases -----------------------------------------------------------------
out.push('-- Phases -------------------------------------------------------------------')
for (const phase of PHASES) {
  out.push(
    `INSERT INTO public.curriculum_phases
   (id, slug, position, title_en, title_ar, summary_en, summary_ar, start_day, end_day, deliverable_en, deliverable_ar)
 VALUES (${q(phaseId(phase.slug))}, ${q(phase.slug)}, ${phase.position}, ${q(phase.titleEn)}, ${q(phase.titleAr)},
         ${q(phase.summaryEn)}, ${q(phase.summaryAr)}, ${phase.startDay}, ${phase.endDay},
         ${q(phase.deliverableEn)}, ${q(phase.deliverableAr)})
ON CONFLICT (id) DO UPDATE SET
   title_en = EXCLUDED.title_en, title_ar = EXCLUDED.title_ar,
   summary_en = EXCLUDED.summary_en, summary_ar = EXCLUDED.summary_ar,
   start_day = EXCLUDED.start_day, end_day = EXCLUDED.end_day,
   deliverable_en = EXCLUDED.deliverable_en, deliverable_ar = EXCLUDED.deliverable_ar;`,
  )
}
out.push('')

// --- Days -------------------------------------------------------------------
out.push('-- Days ---------------------------------------------------------------------')
for (const day of ALL_DAYS) {
  out.push(
    `INSERT INTO public.curriculum_days
   (id, day_number, phase_id, title_en, title_ar, topic, objective_en, objective_ar,
    lesson_en, lesson_ar, estimated_minutes, exercise_en, exercise_ar,
    deliverable_en, deliverable_ar, criteria_en, criteria_ar,
    challenge_en, challenge_ar, prerequisites, kind)
 VALUES (${q(dayId(day.dayNumber))}, ${day.dayNumber}, ${q(phaseId(day.phaseSlug))},
         ${q(day.titleEn)}, ${q(day.titleAr)}, ${q(day.topic)},
         ${q(day.objectiveEn)}, ${q(day.objectiveAr)},
         ${q(day.lessonEn)}, ${q(day.lessonAr)}, ${day.estimatedMinutes},
         ${q(day.exerciseEn)}, ${q(day.exerciseAr)},
         ${q(day.deliverableEn)}, ${q(day.deliverableAr)},
         ${arr(day.criteriaEn)}, ${arr(day.criteriaAr)},
         ${q(day.challengeEn ?? null)}, ${q(day.challengeAr ?? null)},
          ${intArr(day.prerequisites ?? [])}, ${q(day.kind)})
ON CONFLICT (id) DO UPDATE SET
   title_en = EXCLUDED.title_en, title_ar = EXCLUDED.title_ar, topic = EXCLUDED.topic,
   objective_en = EXCLUDED.objective_en, objective_ar = EXCLUDED.objective_ar,
   lesson_en = EXCLUDED.lesson_en, lesson_ar = EXCLUDED.lesson_ar,
   estimated_minutes = EXCLUDED.estimated_minutes,
   exercise_en = EXCLUDED.exercise_en, exercise_ar = EXCLUDED.exercise_ar,
   deliverable_en = EXCLUDED.deliverable_en, deliverable_ar = EXCLUDED.deliverable_ar,
   criteria_en = EXCLUDED.criteria_en, criteria_ar = EXCLUDED.criteria_ar,
   challenge_en = EXCLUDED.challenge_en, challenge_ar = EXCLUDED.challenge_ar,
   prerequisites = EXCLUDED.prerequisites, kind = EXCLUDED.kind;`,
  )
}
out.push('')

// --- Tasks ------------------------------------------------------------------
out.push('-- Tasks --------------------------------------------------------------------')
for (const day of ALL_DAYS) {
  day.tasks.forEach((task, index) => {
    const position = index + 1
    out.push(
      `INSERT INTO public.curriculum_tasks (id, day_id, position, title_en, title_ar)
 VALUES (${q(taskId(day.dayNumber, position))}, ${q(dayId(day.dayNumber))}, ${position}, ${q(task.en)}, ${q(task.ar)})
ON CONFLICT (id) DO UPDATE SET title_en = EXCLUDED.title_en, title_ar = EXCLUDED.title_ar;`,
    )
  })
}
out.push('')

// --- Resources --------------------------------------------------------------
out.push('-- Resources ----------------------------------------------------------------')
for (const day of ALL_DAYS) {
  day.resources.forEach((resource, index) => {
    out.push(
      `INSERT INTO public.learning_resources (id, day_id, title, url, kind, note_en, position)
 VALUES (${q(resourceId(day.dayNumber, index))}, ${q(dayId(day.dayNumber))},
         ${q(resource.title)}, ${q(resource.url)}, ${q(resource.kind)},
         ${q(resource.note ?? null)}, ${index})
ON CONFLICT (id) DO UPDATE SET
   title = EXCLUDED.title, url = EXCLUDED.url, kind = EXCLUDED.kind,
   note_en = EXCLUDED.note_en, position = EXCLUDED.position;`,
    )
  })
}
out.push('')
out.push('COMMIT;')
out.push('')
out.push('-- Sanity check: this should print 365 rows once the remaining phases land.')
out.push('DO $$')
out.push('DECLARE n int;')
out.push('BEGIN')
out.push(`  SELECT count(*) INTO n FROM public.curriculum_days;`)
out.push(`  RAISE NOTICE 'curriculum_days rows: % (of 365)', n;`)
out.push('END $$;')
out.push('')

const target = new URL('../supabase/seed/curriculum.sql', import.meta.url)
mkdirSync(new URL('../supabase/seed/', import.meta.url), { recursive: true })
writeFileSync(target, out.join('\n'), 'utf8')

// Also emit the phase slug -> UUID mapping so the UI can link a project to a
// roadmap phase without hard-coding identifiers in two places. Generated here
// rather than maintained by hand so the two can never drift.
const idsModule = `/**
 * GENERATED FILE — do not edit.
 *
 * Produced by \`npm run seed:curriculum\`. Maps each curriculum phase slug to
 * the deterministic UUID used in the \`curriculum_phases\` table, so the UI can
 * associate a project with a phase without duplicating the id scheme.
 *
 * Regenerate after adding or renaming a phase.
 */
export const PHASE_IDS: Record<string, string> = {
${PHASES.map((phase) => `  '${phase.slug}': '${phaseId(phase.slug)}',`).join('\n')}
}

export function phaseUuid(slug: string): string | null {
  return PHASE_IDS[slug] ?? null
}
`
writeFileSync(new URL('../src/features/curriculum/phase-ids.ts', import.meta.url), idsModule, 'utf8')

console.log(
  `Wrote supabase/seed/curriculum.sql — ${ALL_DAYS.length} days, ` +
    `${ALL_DAYS.reduce((n, d) => n + d.tasks.length, 0)} tasks, ` +
    `${ALL_DAYS.reduce((n, d) => n + d.resources.length, 0)} resources.`,
)
console.log('Wrote src/features/curriculum/phase-ids.ts')